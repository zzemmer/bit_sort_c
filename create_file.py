# Создает файл из 3 записей по 10 байт. Ключ находится в байтах 2-5.
with open("data.bin", "wb") as f:
    f.write(bytes([0x00, 0x22, 0x00, 0x00, 0x00, 0x11, 0x11, 0x11, 0x11, 0x11])) # ключ = 34
    f.write(bytes([0x00, 0x10, 0x00, 0x00, 0x00, 0x22, 0x22, 0x22, 0x22, 0x22])) # ключ = 16
    f.write(bytes([0x00, 0x05, 0x00, 0x00, 0x00, 0x33, 0x33, 0x33, 0x33, 0x33])) # ключ = 5